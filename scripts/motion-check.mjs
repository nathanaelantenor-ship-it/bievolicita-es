import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const html=readFileSync('index.html','utf8');
const css=readFileSync('styles.css','utf8');
const js=readFileSync('script.js','utf8');
assert.equal((html.match(/class="audience-card motion-card"/g)||[]).length,2);
assert.equal((html.match(/class="service motion-card"/g)||[]).length,5);
assert.equal((html.match(/class="testimonial(?: featured)? motion-card"/g)||[]).length,3);
assert(!html.includes('class="service service-cta motion-card"'));
assert(html.includes('Sua empresa pode vender mais.<br/><em>Inclusive para o governo.</em>'));
assert(html.includes('Critério em cada escolha.<br/><em>Organização em cada etapa.</em>'));
assert(css.includes('bievo-hero-breathe'));
assert(css.includes('--hero-zoom:1.023'));
assert(css.includes('.typing-title > .typing-ghost'));
assert(css.includes('background-image:none'));
assert(css.includes('@media(prefers-reduced-motion:reduce)'));
assert(js.includes('IntersectionObserver'));
assert(js.includes("reduceMotion.matches"));
assert(js.includes("closest('a,button')"));
assert(html.includes('O departamento de licitações da sua empresa'));
const release=JSON.parse(readFileSync('release.json','utf8'));
const vercel=JSON.parse(readFileSync('vercel.json','utf8'));
assert.equal(release.release,'bievo-motion-20261105-r2');
assert(html.includes('content="bievo-motion-20261105-r2"'));
assert(html.includes('styles.css?v=bievo-motion-20261105-r2'));
assert(html.includes('script.js?v=bievo-motion-20261105-r2'));
assert(vercel.headers.some(rule=>rule.source==='/' && rule.headers.some(h=>h.key==='Cache-Control')));
console.log('Interações, versão pública e controle de cache: verificações estáticas aprovadas.');
